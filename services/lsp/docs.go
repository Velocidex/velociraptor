/*
   ## How to use this with VS code

   First install the VS code extension as described
   https://github.com/predictiple/velociraptor-lsp-vscode

   Within VS Code:

   1. Offset completion suggestions using CTRL-Space :
      * If the cursor is on a plugin - complete the plugin name.
      * If the cursor is within the plugin args, e.g. plugin( ^ )
        offers arg completion.
   2. Reformat code Shift-Alt-F
   3. Hover over any function/arg to see inline hints
*/
